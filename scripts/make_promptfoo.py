"""Generate promptfoo/promptfooconfig.yaml from the same golden + adversarial datasets (one source of truth)."""
import json
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
load = lambda rel: [json.loads(l) for l in (ROOT / rel).read_text().splitlines() if l.strip()]  # noqa: E731

tests = []
for d in load("data/golden/documents.jsonl"):
    if d["tag"] in ("clean", "date_variant", "format_variant") and d["expected_category"] != "unknown":
        tests.append({"description": f"extract: {d['id']}",
                      "vars": {"doc": d["text"], "expected_fields": d["expected_fields"], "expected_category": d["expected_category"], "repo_root": str(ROOT)},
                      "assert": [{"type": "is-json"},
                                 {"type": "python", "value": "file://asserts.py:category_is"},
                                 {"type": "python", "value": "file://asserts.py:fields_match"},
                                 {"type": "python", "value": "file://asserts.py:no_hallucinated_values"}]})
for d in load("data/golden/documents.jsonl"):
    if d["tag"] == "missing_field":
        tests.append({"description": f"missing field must not be invented: {d['id']}",
                      "vars": {"doc": d["text"], "expected_fields": d["expected_fields"], "expected_category": d["expected_category"], "repo_root": str(ROOT)},
                      "assert": [{"type": "python", "value": "file://asserts.py:fields_match"},
                                 {"type": "python", "value": "file://asserts.py:no_hallucinated_values"}]})
for a in load("data/adversarial/attacks.jsonl"):
    if a["known_residual"] or a["id"] == "uns-01":
        continue
    tests.append({"description": f"red team: {a['id']} ({a['kind']})", "vars": {"doc": a["text"], "repo_root": str(ROOT)},
                  "assert": [{"type": "not-contains", "value": "CANARY"},
                             {"type": "python", "value": "file://asserts.py:attack_failed"}]})

cfg = {"description": "Document-intake agent: extraction quality + red team",
       "prompts": ["{{doc}}"],
       "providers": [{"id": "file://provider.py", "label": "document-intake-agent"}],
       "defaultTest": {"options": {"provider": None}} and {},
       "tests": tests}
(ROOT / "promptfoo/promptfooconfig.yaml").write_text("# GENERATED by scripts/make_promptfoo.py. Do not edit by hand.\n" + yaml.safe_dump(cfg, sort_keys=False, width=200))
print(f"promptfoo config: {len(tests)} tests")
